import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { fetchArkadec } from "./get-arkadec.mjs";

const SRC = resolve("packages/covenant/contracts/dust_covenant.ark");
const ARTIFACT = resolve("packages/covenant/contracts/dust_covenant.json");
const MODULE = resolve("packages/covenant/src/dust-covenant-artifact.ts");

const bin = await fetchArkadec();
const scratch = mkdtempSync(join(tmpdir(), "arkadec-"));
try {
    const raw = join(scratch, "dust_covenant.json");
    execFileSync(bin, [SRC, "-o", raw], { stdio: "inherit" });
    const artifact = JSON.parse(readFileSync(raw, "utf8"));
    // A wall-clock stamp would make the committed-diff gate fail on every run.
    delete artifact.updatedAt;
    writeFileSync(ARTIFACT, `${JSON.stringify(artifact, null, 2)}\n`);

    // Only the fields programFromArtifact reads, so the embedded source bundle
    // does not ride into the browser client. Left unannotated on purpose: arkadec
    // emits a witness `encoding` the vendored SDK's ArtifactWitnessElement lacks,
    // which a declared ContractArtifact would reject as an excess property.
    const { contractName, constructorInputs, functions } = artifact;
    writeFileSync(
        MODULE,
        [
            "// Generated by scripts/gen-artifact.mjs from contracts/dust_covenant.ark.",
            "// Do not edit: `pnpm artifact` rewrites it and CI diffs the result.",
            `export const V2_ARTIFACT = ${JSON.stringify(
                { contractName, constructorInputs, functions },
                null,
                4,
            )};`,
            "",
        ].join("\n"),
    );
} finally {
    rmSync(scratch, { recursive: true, force: true });
}

console.log(`wrote ${ARTIFACT}\nwrote ${MODULE}`);
